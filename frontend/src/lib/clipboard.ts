// Copiar texto al portapapeles. navigator.clipboard solo existe en contextos
// seguros (HTTPS o localhost); el panel se suele abrir por HTTP en la LAN, así
// que hace falta el método antiguo como alternativa.

export async function copyText(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Sin permiso: se prueba con el método antiguo
    }
  }
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  try {
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    area.remove();
  }
}
